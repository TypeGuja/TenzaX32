//! Автоматический поворот (раздел 8 ТЗ): "вместо хранения кадров под
//! разными углами — пересчитать перспективу". Здесь — не полноценная
//! 3D-модель, а честная, ограниченная имитация: каждая часть персонажа —
//! плоская карточка на условном поворотном круге. Поворот персонажа на
//! угол `yaw` пересчитывает для каждой карточки:
//! 1. горизонтальный масштаб (foreshortening — карточка "сжимается" по X,
//!    когда поворачивается к нам ребром);
//! 2. горизонтальное смещение позиции (parallax — части, которые дальше
//!    от центра по условной глубине, сильнее сдвигаются при повороте).
//!
//! Ограничения, честно: это плоские карточки, не настоящий меш, поэтому
//! нет самозаслонения объёмных деталей (нос не загораживает щёку) и после
//! ~90° карточка не "переворачивается" на другую сторону — просто
//! схлопывается до минимальной ширины (см. `MIN_FORESHORTEN`). Для полного
//! разворота на 180° потребовалась бы отдельная арт-сторона (спина) —
//! этого пока нет, как и в исходном ТЗ не описан этот случай отдельно.

/// Минимальная видимая ширина части при повороте почти в профиль (90°) —
/// не даём ей схлопнуться в невидимую линию. Грубая имитация того, что
/// даже "плоская" карточка (перо, ухо) имеет какую-то толщину.
const MIN_FORESHORTEN: f32 = 0.15;

/// Пересчитать экранную X-позицию и горизонтальный масштаб (foreshortening)
/// части персонажа, повёрнутого на угол `yaw` (радианы, 0 = анфас,
/// положительное — поворот вправо). `local_x` — исходная X-позиция части
/// относительно центра персонажа; `depth_z` — условная глубина части
/// (насколько она "выступает" вперёд/назад от центра) — в `pony-render`
/// выводится из `layer` части (отдельного поля глубины в модели нет).
///
/// Возвращает `(новый_x, множитель_ширины)`.
pub fn apply_yaw_2_5d(local_x: f32, depth_z: f32, yaw: f32) -> (f32, f32) {
    let (sin, cos) = yaw.sin_cos();
    let rotated_x = local_x * cos - depth_z * sin;
    let foreshorten = cos.abs().max(MIN_FORESHORTEN);
    (rotated_x, foreshorten)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn zero_yaw_is_identity() {
        let (x, scale) = apply_yaw_2_5d(10.0, 5.0, 0.0);
        assert!((x - 10.0).abs() < 1e-4, "x={x}");
        assert!((scale - 1.0).abs() < 1e-4, "scale={scale}");
    }

    #[test]
    fn ninety_degrees_clamps_foreshorten_but_does_not_vanish() {
        let (_, scale) = apply_yaw_2_5d(10.0, 0.0, std::f32::consts::FRAC_PI_2);
        assert!((scale - MIN_FORESHORTEN).abs() < 1e-3, "scale={scale}");
        assert!(scale > 0.0);
    }

    #[test]
    fn depth_shifts_position_more_as_yaw_increases() {
        let (x_small_yaw, _) = apply_yaw_2_5d(0.0, 10.0, 0.1);
        let (x_big_yaw, _) = apply_yaw_2_5d(0.0, 10.0, 0.8);
        assert!(
            x_big_yaw.abs() > x_small_yaw.abs(),
            "часть с ненулевой глубиной должна сильнее смещаться при большем повороте: {x_small_yaw} vs {x_big_yaw}"
        );
    }

    #[test]
    fn zero_depth_never_shifts_regardless_of_yaw() {
        // Часть точно по центру глубины (depth_z=0, как тело) не должна
        // сдвигаться по X от поворота — только сжиматься по ширине.
        for deg in [10.0f32, 45.0, 80.0] {
            let (x, _) = apply_yaw_2_5d(0.0, 0.0, deg.to_radians());
            assert!(x.abs() < 1e-4, "x={x} at {deg} deg");
        }
    }

    #[test]
    fn foreshorten_shrinks_monotonically_from_0_to_90_degrees() {
        let mut prev = 1.0f32;
        for deg in [10.0f32, 30.0, 50.0, 70.0, 89.0] {
            let (_, scale) = apply_yaw_2_5d(0.0, 0.0, deg.to_radians());
            assert!(scale <= prev + 1e-4, "foreshorten должен монотонно уменьшаться: {scale} > {prev} at {deg} deg");
            prev = scale;
        }
    }
}
