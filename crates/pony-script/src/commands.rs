//! Команды, которые может испустить скрипт (раздел 15 ТЗ:
//! `pony.Move()`, `pony.Look()`, `pony.Blink()`, `pony.Smile()`,
//! `pony.Walk()`, `camera.Zoom()`, `camera.Shake()`).
//!
//! Скрипт НЕ мутирует `Character`/`Camera` напрямую — он только описывает
//! намерение (`Command`), а `apply_commands` в `lib.rs` применяет их к
//! реальному состоянию. Это разделение позволяет: (а) тестировать скрипт
//! независимо от рендера/состояния, (б) записывать/воспроизводить команды,
//! (в) не тащить `Rc<RefCell<Character>>` в rhai, где типы должны быть
//! дешёвыми для клонирования.

#[derive(Debug, Clone, PartialEq)]
pub enum Command {
    /// Сдвинуть персонажа на (dx, dy) в мировых координатах.
    Move { dx: f32, dy: f32 },
    /// Развернуть "взгляд" — пока сохраняется как есть, применяется как
    /// поворот кости головы (упрощение; настоящий взгляд — это отдельный
    /// прицел глаз через морфинг, не поворот всей головы).
    Look { x: f32, y: f32 },
    /// Разовое моргание — выставляет морф-вес "Blink" в 1.0.
    /// Настоящая анимация моргания (открыть -> закрыть -> открыть) —
    /// это уже `Animation`, а не разовая команда; здесь только триггер.
    Blink,
    /// Морф-вес "Smile" в диапазоне 0..1.
    Smile { amount: f32 },
    /// Запустить именованную анимацию ходьбы, если она есть у персонажа.
    Walk,
    CameraMove { dx: f32, dy: f32 },
    CameraRotate { radians: f32 },
    /// Множитель к текущему зуму камеры.
    CameraZoom { factor: f32 },
    CameraShake { intensity: f32 },
    CameraDepth { value: f32 },
    CameraBlur { value: f32 },
}
